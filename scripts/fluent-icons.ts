function packageDir(): string {
  const given = process.env['TRIYA_FLUENT_DIR'];
  if (given) return given;
  const dir = mkdtempSync(path.join(tmpdir(), 'fluent-'));
  execFileSync('npm', ['pack', `@fluentui/svg-icons@${VERSION}`, '--pack-destination', dir], {
    stdio: 'ignore',
  });
  execFileSync('tar', ['xzf', `fluentui-svg-icons-${VERSION}.tgz`], { cwd: dir });
  return path.join(dir, 'package');
}

const dir = packageDir();
const lines = NAMES.map((name) => {
  const svg = readFileSync(path.join(dir, 'icons', `${name}_20_regular.svg`), 'utf8');
  if (/<g|transform|fill-rule|clip/.test(svg)) throw new Error(`${name}: not a plain path icon`);
  const d = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]).join('');
  if (!d) throw new Error(`${name}: no path`);
  return `  ${name}: '${d}',`;
});

const out = path.join(import.meta.dirname, '../apps/web/src/ribbon/fluent-icons.ts');
writeFileSync(
  out,
  `// Generated by scripts/fluent-icons.ts from @fluentui/svg-icons ${VERSION}: do not edit.
// Fluent UI System Icons, 20 px regular, filled path data on a 20 × 20 grid.
// MIT License, Copyright (c) 2020 Microsoft Corporation (ATTRIBUTION.md).
// prettier-ignore
export const FLUENT_ICONS = {
${lines.join('\n')}
} as const;

export type FluentIconName = keyof typeof FLUENT_ICONS;
`,
);
