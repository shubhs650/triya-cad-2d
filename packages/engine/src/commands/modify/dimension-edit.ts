type Sub<T> = AsyncGenerator<Prompt, T, PromptAnswer>;

type Linear = Extract<DimensionGeometry, { dimType: 'linear' | 'aligned' }>;

const isLinear = (e: Entity): e is Entity & { geom: Linear } =>
  e.geom.kind === 'DIMENSION' && (e.geom.dimType === 'linear' || e.geom.dimType === 'aligned');

/** `p` moved onto the dimension line of `g`. */
function onDimensionLine(g: Linear, p: Vec2): Vec2 {
  const u = dimensionDirection(g);
  const o = g.definitionPoint;
  return add(o, scale(u, dot(sub(p, o), u)));
}

/**
 * Where DIMJOGLINE puts a jog when Enter is pressed: "at a midpoint between the dimension text
 * and the first extension line" (AutoCAD 2024 Help, DIMJOGLINE), on the dimension line.
 */
export function defaultJogLocation(g: Linear): Vec2 {
  const [first] = dimensionLineEnds(g);
  return midpoint(first, onDimensionLine(g, g.textPosition));
}

/** The dimension's xdata without its jog. */
function withoutJog(xdata: Xdata | undefined, ctx: CommandContext): Xdata | undefined {
  const out = (xdata ?? []).filter(
    (a) => ctx.model.tables.appIds.get(a.appId)?.name.toUpperCase() !== LINEAR_JOG_APP,
  );
  return out.length > 0 ? out : undefined;
}

/** Sets a dimension's xdata and has the engine draw it again. */
async function restyle(ctx: CommandContext, e: Entity, xdata: Xdata | undefined): Promise<void> {
  ctx.edit((b) => {
    b.updateEntity(e.id, { xdata });
  });
  await regenerateDimensions(ctx, [e.id]);
}

function jogLineCommand(): CommandDef {
  return {
    name: 'DIMJOGLINE',
    usesSelection: 'none',
    async *run(ctx): CommandGenerator {
      for (;;) {
        const a = yield ctx.prompt.selection({
          message: 'Select dimension to add jog or',
          single: true,
          options: ['Remove'],
        });
        if (a.kind === 'keyword' && a.keyword === 'Remove') {
          for (;;) {
            const o = yield* pickObject(ctx, 'Select jog to remove');
            if (o === undefined || o === 'enter') return;
            if (!isLinear(o.entity) || !linearJog(o.entity.xdata, ctx.model)) {
              ctx.message('Object selected is not a jogged dimension.');
              continue;
            }
            await restyle(ctx, o.entity, withoutJog(o.entity.xdata, ctx));
            return;
          }
        }
        if (a.kind !== 'selection' || a.ids.length === 0) return;
        const e = ctx.model.entity(a.ids[0]!);
        if (!e || !isLinear(e)) {
          ctx.message('Object selected is not a linear or aligned dimension.');
          continue;
        }
        const at = yield ctx.prompt.point({ message: 'Specify jog location (or press ENTER)' });
        if (at.kind !== 'point' && at.kind !== 'enter') return;
        const where =
          at.kind === 'point' ? onDimensionLine(e.geom, at.point) : defaultJogLocation(e.geom);
        const appId = appIdNamed(ctx, LINEAR_JOG_APP);
        await restyle(ctx, e, withLinearJog(e.xdata, appId, where));
        return;
      }
    },
  };
}

const isDimension = (e: Entity): e is Entity & { geom: DimensionGeometry } =>
  e.geom.kind === 'DIMENSION' ||
  e.geom.kind === 'ARC_DIMENSION' ||
  e.geom.kind === 'LARGE_RADIAL_DIMENSION';

/** "Select objects": the dimensions among them; undefined when the command ends. */
async function* selectDimensions(ctx: CommandContext): Sub<Entity[] | undefined> {
  const a = yield ctx.prompt.selection({ message: 'Select objects', editable: true });
  if (a.kind !== 'selection') return undefined;
  const out: Entity[] = [];
  for (const id of a.ids) {
    const e = ctx.model.entity(id);
    if (e && isDimension(e)) out.push(e);
  }
  return out;
}

/** Changes each dimension of `dims` by `change` and has the engine draw the changed ones again. */
async function changeDimensions(
  ctx: CommandContext,
  dims: readonly Entity[],
  change: (e: Entity & { geom: DimensionGeometry }) => EntityPatch,
): Promise<void> {
  const changed: EntityId[] = [];
  ctx.edit((b) => {
    for (const e of dims) {
      const now = b.entity(e.id);
      if (!now || !isDimension(now)) continue;
      const patch = change(now);
      if (Object.keys(patch).length === 0) continue;
      b.updateEntity(e.id, patch);
      changed.push(e.id);
    }
  });
  await regenerateDimensions(ctx, changed);
}

/**
 * DIMEDIT. Home: "Moves rotated dimension text back to its default position"; New: the text
 * given replaces each dimension's, `<>` standing for its measurement; Rotate: "Rotates
 * dimension text"; Oblique: "Adjusts the oblique angle of the extension lines for linear
 * dimensions" (AutoCAD 2024 Help, DIMEDIT). Only linear and aligned dimensions have extension
 * lines to slant; an angle of 0, or Enter, takes the slant off.
 */
function dimeditCommand(): CommandDef {
  return {
    name: 'DIMEDIT',
    usesSelection: 'none',
    async *run(ctx): CommandGenerator {
      const a = yield ctx.prompt.keyword({
        message: 'Enter type of dimension editing',
        options: ['Home', 'New', 'Rotate', 'Oblique'],
        default: { kind: 'keyword', keyword: 'Home' },
      });
      if (a.kind !== 'keyword') return;
      let change: Parameters<typeof changeDimensions>[2];
      switch (a.keyword) {
        case 'New': {
          const t = yield ctx.prompt.string({
            message: 'Enter dimension text',
            spaces: true,
            default: { kind: 'string', value: '<>' },
          });
          if (t.kind !== 'string') return;
          const text = dimensionOverride(t.value);
          change = (e) => (e.geom.text === text ? {} : { geom: { ...e.geom, text } });
          break;
        }
        case 'Rotate': {
          const r = yield ctx.prompt.angle({ message: 'Specify angle for dimension text' });
          if (r.kind !== 'angle') return;
          change = (e) => ({ geom: { ...e.geom, textRotation: r.value } });
          break;
        }
        case 'Oblique':
          change = undefined!;
          break;
        default:
          change = (e) => ({ geom: { ...e.geom, textRotation: 0, textUserPositioned: false } });
      }
      const dims = yield* selectDimensions(ctx);
      if (!dims || dims.length === 0) return;
      if (a.keyword === 'Oblique') {
        const o = yield ctx.prompt.angle({
          message: 'Enter obliquing angle (press ENTER for none)',
        });
        if (o.kind !== 'angle' && o.kind !== 'enter') return;
        const angle = o.kind === 'angle' ? o.value : 0;
        change = (e) => {
          const g = e.geom;
          if (g.kind !== 'DIMENSION' || (g.dimType !== 'linear' && g.dimType !== 'aligned')) {
            return {};
          }
          // An extension line along the dimension line is no extension line.
          const u = dimensionDirection(g);
          if (angle !== 0 && Math.abs(Math.sin(angle - Math.atan2(u.y, u.x))) < 1e-9) return {};
          const { oblique: _o, ...plain } = g;
          return { geom: angle === 0 ? plain : { ...g, oblique: angle } };
        };
      }
      await changeDimensions(ctx, dims, change);
    },
  };
}

/** DIMJUST for DIMTEDIT's Left, Right and Center (AutoCAD 2024 Help, DIMJUST). */
const JUSTIFY: Readonly<Record<string, number>> = { Left: 1, Right: 2, Center: 0 };

/**
 * DIMTEDIT: the dimension's text dragged to a new location (kept there, DXF 70 bit 128), or
 * Left, Right and Center along the dimension line, Home, or Angle. AutoCAD 2024 Help, DIMTEDIT:
 * Left and Right "work only with linear, radial, and diameter dimensions"; they are filed as a
 * DIMJUST override with the text sent home, which is what that DIMVAR does to text the style
 * places (our reading: AutoCAD's help does not say how it keeps them). Center as DIMJUST 0.
 */
function dimteditCommand(): CommandDef {
  return {
    name: 'DIMTEDIT',
    usesSelection: 'none',
    async *run(ctx): CommandGenerator {
      let e: (Entity & { geom: DimensionGeometry }) | undefined;
      while (!e) {
        const o = yield* pickObject(ctx, 'Select dimension');
        if (o === undefined || o === 'enter') return;
        if (isDimension(o.entity)) e = o.entity;
        else ctx.message('Object selected is not a dimension.');
      }
      const g = e.geom;
      const linear =
        g.kind === 'DIMENSION' &&
        (g.dimType === 'linear' ||
          g.dimType === 'aligned' ||
          g.dimType === 'radius' ||
          g.dimType === 'diameter');
      const a = yield ctx.prompt.point({
        message: 'Specify new location for dimension text or',
        options: ['Left', 'Right', 'Center', 'Home', 'Angle'],
        drag: { kind: 'grip', ids: [e.id], grip: g.textPosition, from: g.textPosition },
      });
      let change: Parameters<typeof changeDimensions>[2];
      if (a.kind === 'point') {
        change = (d) => ({
          geom: { ...d.geom, textPosition: a.point, textUserPositioned: true },
        });
      } else if (a.kind !== 'keyword') {
        return;
      } else if (a.keyword === 'Home') {
        change = (d) => ({ geom: { ...d.geom, textUserPositioned: false } });
      } else if (a.keyword === 'Angle') {
        const r = yield ctx.prompt.angle({ message: 'Specify angle for dimension text' });
        if (r.kind !== 'angle') return;
        change = (d) => ({ geom: { ...d.geom, textRotation: r.value } });
      } else {
        if (a.keyword !== 'Center' && !linear) {
          ctx.message('Left and Right work only with linear, radial and diameter dimensions.');
          return;
        }
        const just = JUSTIFY[a.keyword]!;
        change = (d) => {
          const x = withDimvarOverride(d, d.geom.style, ctx.model, 'DIMJUST', just, 0);
          return {
            geom: { ...d.geom, textUserPositioned: false },
            ...(x !== 'no-acad' && { xdata: x }),
          };
        };
      }
      await changeDimensions(ctx, [e], change);
    },
  };
}

const CODE_OF: Readonly<Record<string, number>> = Object.fromEntries(
  Object.entries(DIMVAR_BY_CODE).map(([code, name]) => [name, Number(code)]),
);

/** The records a handle DIMVAR (DXF 340–347) names, by name. */
function namedRecords(ctx: CommandContext, code: number) {
  if (code === 340) return [...ctx.model.tables.textStyles.values()];
  if (code >= 341 && code <= 344) return [...ctx.model.blocks.values()];
  return [...ctx.model.tables.linetypes.values()];
}

/**
 * What DIMOVERRIDE files for DIMVAR `name` typed as `text`; a string saying what is wrong when
 * it cannot be. Reals for codes 40–59 and 140–149, names of text styles, blocks or linetypes
 * for 340–347 (`.` or nothing for none), DIMDSEP's character as its code, integers otherwise.
 */
export function dimvarValue(
  ctx: CommandContext,
  name: string,
  text: string,
): DimVarValue | { error: string } {
  const code = CODE_OF[name]!;
  const t = text.trim();
  if (code === 3 || code === 4) return text;
  if (name === 'DIMDSEP') {
    return t.length === 1 ? t.charCodeAt(0) : { error: 'Requires a single character.' };
  }
  if (code >= 340 && code <= 349) {
    if (t === '' || t === '.') return '';
    const r = namedRecords(ctx, code).find((x) => x.name.toUpperCase() === t.toUpperCase());
    return r ? r.handle : { error: `${t} not found.` };
  }
  const n = Number(t);
  if (t === '' || !Number.isFinite(n)) return { error: 'Requires a number.' };
  const real = (code >= 40 && code <= 59) || (code >= 140 && code <= 149);
  if (!real && !Number.isInteger(n)) return { error: 'Requires an integer.' };
  return n;
}

/** How the header shows DIMVAR `name`'s current value: a record's name for a handle DIMVAR. */
function currentValue(ctx: CommandContext, name: string): string {
  const v = ctx.model.header.get(`$${name}`);
  if (v === undefined || typeof v === 'object') return '';
  if (name === 'DIMDSEP' && typeof v === 'number') return String.fromCharCode(v);
  if (typeof v === 'boolean') return v ? '1' : '0';
  return String(v);
}

/**
 * `e`'s xdata with its DIMVAR overrides removed: each set back to what its style says (or
 * dropped where the style says nothing), so its other xdata stays as it is.
 */
function withoutOverrides(e: Entity & { geom: DimensionGeometry }, ctx: CommandContext) {
  let x: { readonly xdata?: Xdata } = e;
  const styled = dimVars(e.geom.style, undefined, ctx.model);
  for (const [name, value] of Object.entries(dstyleOverrides(e.xdata, ctx.model))) {
    const back = styled[name] ?? value;
    const r = withDimvarOverride(x, e.geom.style, ctx.model, name, back, back);
    if (r === 'no-acad') return e.xdata;
    x = r === undefined ? {} : { xdata: r };
  }
  return x.xdata;
}

/**
 * DIMOVERRIDE: "Controls overrides of system variables used in selected dimensions" (AutoCAD
 * 2024 Help, DIMOVERRIDE): DIMVARs and their values until Enter, then the dimensions they go
 * on; Clear overrides takes every override off the dimensions selected.
 */
function dimoverrideCommand(): CommandDef {
  return {
    name: 'DIMOVERRIDE',
    usesSelection: 'none',
    async *run(ctx): CommandGenerator {
      const overrides: [string, DimVarValue][] = [];
      for (;;) {
        const a = yield ctx.prompt.string({
          message: 'Enter dimension variable name to override or',
          options: ['Clear overrides'],
        });
        if (a.kind === 'keyword') {
          const dims = yield* selectDimensions(ctx);
          if (!dims || dims.length === 0) return;
          await changeDimensions(ctx, dims, (e) => {
            const xdata = withoutOverrides(e, ctx);
            return xdata === e.xdata ? {} : { xdata };
          });
          return;
        }
        if (a.kind === 'enter') break;
        if (a.kind !== 'string') return;
        const name = a.value.trim().toUpperCase();
        if (name === '') break;
        if (CODE_OF[name] === undefined || name === 'DIMFIT' || name === 'DIMUNIT') {
          ctx.message('Unknown dimension variable name.');
          continue;
        }
        for (;;) {
          const current = currentValue(ctx, name);
          const v = yield ctx.prompt.string({
            message: 'Enter new value for dimension variable',
            spaces: CODE_OF[name] === 3 || CODE_OF[name] === 4,
            default: { kind: 'string', value: current },
          });
          if (v.kind !== 'string') return;
          const value = dimvarValue(ctx, name, v.value);
          if (typeof value === 'object') {
            ctx.message(value.error);
            continue;
          }
          overrides.push([name, value]);
          break;
        }
      }
      if (overrides.length === 0) return;
      const dims = yield* selectDimensions(ctx);
      if (!dims || dims.length === 0) return;
      let noAcad = false;
      await changeDimensions(ctx, dims, (e) => {
        let x: { readonly xdata?: Xdata } = e;
        for (const [name, value] of overrides) {
          const r = withDimvarOverride(
            x,
            e.geom.style,
            ctx.model,
            name,
            value,
            DIMVAR_DEFAULTS[name],
          );
          if (r === 'no-acad') {
            noAcad = true;
            return {};
          }
          x = r === undefined ? {} : { xdata: r };
        }
        return x.xdata === e.xdata ? {} : { xdata: x.xdata };
      });
      if (noAcad) ctx.message('The drawing has no ACAD application to file overrides under.');
    },
  };
}

/**
 * The Health palette's Clear Overrides (M8-07 part 2): DIMOVERRIDE's Clear overrides on every
 * dimension that has overrides in model space and the layouts, outside locked layers
 * (`overriddenDimensions`), as one DIMOVERRIDE undo step that redraws them.
 */
export function clearDimensionOverridesCommand(): CommandDef {
  return {
    name: 'DIMOVERRIDE',
    usesSelection: 'none',
    keepsSelection: true,
    // eslint-disable-next-line require-yield -- the palette named the dimensions
    async *run(ctx) {
      const dims = overriddenDimensions(ctx.model).map((id) => ctx.model.entity(id)!);
      if (dims.length === 0) {
        ctx.message('No dimensions with style overrides found.');
        return;
      }
      await changeDimensions(ctx, dims, (e) => {
        const xdata = withoutOverrides(e, ctx);
        return xdata === e.xdata ? {} : { xdata };
      });
      ctx.message(
        `Overrides cleared from ${dims.length} ${dims.length === 1 ? 'dimension' : 'dimensions'}.`,
      );
    },
  };
}

/**
 * Where DIMSPACE puts each dimension of `dims` from `base`: `spacing` apart, in the order they
 * stand from it, on the side each is on (AutoCAD 2024 Help, DIMSPACE: "Adjusts the spacing
 * between linear dimensions or angular dimensions", 0 lining them up with the base). Linear and
 * aligned dimensions running the base's way move their dimension line across; angular and arc
 * length dimensions about the base's centre take their arc in or out. Those that are neither
 * are left out.
 */
export function spacedDimensions(
  base: DimensionGeometry,
  dims: readonly (Entity & { geom: DimensionGeometry })[],
  spacing: number,
): Map<Entity, DimensionGeometry> {
  const out = new Map<Entity, DimensionGeometry>();
  const place = (offsets: { e: Entity; at: number }[], move: (e: Entity, to: number) => void) => {
    for (const sign of [1, -1]) {
      const side = offsets
        .filter((o) => Math.sign(o.at) === sign)
        .sort((a, b) => sign * (a.at - b.at));
      side.forEach((o, i) => move(o.e, sign * (i + 1) * spacing));
    }
    for (const o of offsets) if (o.at === 0) move(o.e, 0);
  };
  if (base.kind === 'DIMENSION' && (base.dimType === 'linear' || base.dimType === 'aligned')) {
    const u = dimensionDirection(base);
    const n = perp(u);
    const offsets: { e: Entity; at: number }[] = [];
    for (const e of dims) {
      const g = e.geom;
      if (g.kind !== 'DIMENSION' || (g.dimType !== 'linear' && g.dimType !== 'aligned')) continue;
      if (Math.abs(cross(dimensionDirection(g), u)) > 1e-9) continue;
      offsets.push({ e, at: dot(sub(g.definitionPoint, base.definitionPoint), n) });
    }
    place(offsets, (e, to) => {
      const g = e.geom as DimensionGeometry & { dimType: 'linear' | 'aligned' };
      const d = scale(n, to - dot(sub(g.definitionPoint, base.definitionPoint), n));
      out.set(e, {
        ...g,
        definitionPoint: add(g.definitionPoint, d),
        ...(g.textUserPositioned && { textPosition: add(g.textPosition, d) }),
      });
    });
    return out;
  }
  const arc = isArcDimension(base) ? dimensionArcOf(base) : undefined;
  if (!arc) return out;
  const offsets: { e: Entity; at: number }[] = [];
  for (const e of dims) {
    const g = e.geom;
    const a = isArcDimension(g) ? dimensionArcOf(g) : undefined;
    if (!a || distance(a.centre, arc.centre) > 1e-9 * Math.max(1, arc.radius)) continue;
    offsets.push({ e, at: a.radius - arc.radius });
  }
  place(offsets, (e, to) => {
    const g = withArcRadius(e.geom as Parameters<typeof withArcRadius>[0], arc.radius + to);
    if (g) out.set(e, g);
  });
  return out;
}

function dimspaceCommand(): CommandDef {
  return {
    name: 'DIMSPACE',
    usesSelection: 'none',
    async *run(ctx): CommandGenerator {
      let base: (Entity & { geom: DimensionGeometry }) | undefined;
      while (!base) {
        const o = yield* pickObject(ctx, 'Select base dimension');
        if (o === undefined || o === 'enter') return;
        const g = o.entity.geom;
        const ok =
          isDimension(o.entity) &&
          ((g.kind === 'DIMENSION' && (g.dimType === 'linear' || g.dimType === 'aligned')) ||
            isArcDimension(g));
        if (ok) base = o.entity as Entity & { geom: DimensionGeometry };
        else ctx.message('Object selected is not a linear or angular dimension.');
      }
      const a = yield ctx.prompt.selection({
        message: 'Select dimensions to space',
        editable: true,
      });
      if (a.kind !== 'selection') return;
      const dims: (Entity & { geom: DimensionGeometry })[] = [];
      for (const id of a.ids) {
        const e = ctx.model.entity(id);
        if (e && e.id !== base.id && isDimension(e)) dims.push(e);
      }
      if (dims.length === 0) return;
      const v = yield ctx.prompt.distance({
        message: 'Enter value or',
        options: ['Auto'],
        default: { kind: 'keyword', keyword: 'Auto' },
      });
      let spacing: number;
      if (v.kind === 'distance') spacing = Math.abs(v.value);
      else if (v.kind === 'keyword') {
        // "Twice the height of the dimension text" of the base's style (AutoCAD 2024 Help).
        spacing = 2 * dimensionTextHeight(ctx.model, base.geom, base.xdata);
      } else return;
      const moved = spacedDimensions(base.geom, dims, spacing);
      await changeDimensions(ctx, [...moved.keys()], (e) => {
        const g = moved.get(dims.find((d) => d.id === e.id)!);
        return g ? { geom: g } : {};
      });
    },
  };
}

export function dimensionEditCommands(): CommandDef[] {
  return [
    jogLineCommand(),
    dimeditCommand(),
    dimteditCommand(),
    dimoverrideCommand(),
    dimspaceCommand(),
  ];
}
