// Commands that change dimensions already drawn (M4-02), with AutoCAD 2024's prompts (AutoCAD
// 2024 Help, "DIMJOGLINE (Command)", "DIMEDIT (Command)", "DIMTEDIT (Command)", "DIMOVERRIDE
// (Command)"):
//   DIMJOGLINE   Select dimension to add jog or [Remove]:
//                Specify jog location (or press ENTER):
//                Remove: Select jog to remove:
//   DIMEDIT      Enter type of dimension editing [Home/New/Rotate/Oblique] <Home>:
//                Select objects:
//   DIMTEDIT     Select dimension:
//                Specify new location for dimension text or [Left/Right/Center/Home/Angle]:
//   DIMOVERRIDE  Enter dimension variable name to override or [Clear overrides]:
//                Enter new value for dimension variable <current>:
//                Select objects:
//   DIMSPACE     Select base dimension:
//                Select dimensions to space:
//                Enter value or [Auto] <Auto>:
// A changed dimension is regenerated by the dimension engine in the same command, so one undo
// takes the change back with its graphics.
