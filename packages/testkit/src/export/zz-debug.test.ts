import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { DocumentModel, PromptBus, builtinCommands } from '@triya/engine';
import { documentInit, readCadDocument } from '@triya/io';
import { it } from 'vitest';
import { withPinnedClock } from '../roundtrip/clock.ts';
import { saveAc1032Dxf } from '../dxf-audit/saves.ts';
const corpusDir = fileURLToPath(new URL('../../../../corpus/', import.meta.url));
it('dbg', async () => {
  const path = 'public/third-party/ezdxf/examples_dxf/mtext_complex_inline_codes.dxf';
  const bytes = new Uint8Array(readFileSync(`${corpusDir}${path}`));
  const model = withPinnedClock(() => DocumentModel.create(documentInit(readCadDocument(bytes))));
  const space = model.layouts.find((l) => l.name === 'Model')!.blockRecord;
  const ids = model.blockEntities(space).slice(0, 5);
  console.log(ids.map((id) => [model.entity(id)!.geom.kind, model.entity(id)!.extDict, !!(model.entity(id)!.geom as {field?:unknown}).field]));
  const bus = new PromptBus({ model, registry: builtinCommands(), space: () => space });
  await bus.script(['COPY']);
  await bus.answer({ kind: 'selection', ids });
  await bus.script(['0,0', '100,0', '']);
  await bus.script(['ERASE']);
  await bus.answer({ kind: 'selection', ids });
  console.log(bus.history.slice(-6));
  writeFileSync('/tmp/claude-0/copy.dxf', withPinnedClock(() => saveAc1032Dxf(readCadDocument(bytes), model)));
});
