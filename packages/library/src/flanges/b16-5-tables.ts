// ASME B16.5-2020 pipe flange dimensions, inch tables (classes 150 to 2500, NPS ½ to 24).
//
// Source: ASME B16.5-2020, "Pipe Flanges and Flanged Fittings", the inch dimension tables for
// flanges (Mandatory Appendix II: Class 150 Table II-8, 300 II-11, 400 II-14, 600 II-17,
// 900 II-20, 1500 II-23, 2500 II-26) and the socket-welding and threaded flange tables that go
// with them. The values were transcribed from Texas Flange's published B16.5 charts
// (texasflange.com, "ASME B16.5 Class N Flange Dimensions", read 2026-11-28) and cross-checked
// against engineeringtoolbox.com's B16.5 bolting table (O, bolt count and size, hole, bolt
// circle for every class and size), API International's Class 150 and 300 weld neck, slip-on
// and blind charts (apiint.com) and Thermometrics' Class 900 and 1500 charts. Where the sources
// disagreed the majority was kept; see packages/library/README.md, "Provenance". Dimensions
// are facts of the standard; no table layout or text of the standard is reproduced.
//
// Every length is in inches as the standard prints it (two decimals). B16.5's flange thickness
// tf and lengths through the hub Y exclude the raised face (0.06 in. for Classes 150 and 300,
// 0.25 in. for 400 and up); the lap joint flange has no raised face. `null`: the standard
// gives no such flange (or dimension) in that size.
//
// Columns, with B16.5's symbols:
//   nps    nominal pipe size
//   O      outside diameter of the flange
//   tf     minimum flange thickness (weld neck, slip-on, threaded, socket welding, blind)
//   tfLap  lap joint flange thickness, Classes 150 and 300 (Classes 400 and up: tf)
//   R      diameter of the raised face
//   X      diameter of the hub at its base
//   holes  number of bolt holes
//   hole   diameter of the bolt holes (bolt diameter + 1/8 in.)
//   W      diameter of the bolt circle
//   bSO    bore B of slip-on and socket welding flanges (the socket's diameter)
//   bLap   bore B of the lap joint flange
//   A      diameter of the hub at the weld point (the pipe's outside diameter)
//   ySO    length through hub Y of slip-on, threaded and socket welding flanges
//   yWN    length through hub Y of the weld neck flange
//   yLap   length through hub Y of the lap joint flange
//   r      radius of the lap joint flange's bore corner
//   q      counterbore diameter Q of the threaded flange
//   d      depth of socket D (socket welding flanges, NPS ½ to 3)
//   t      minimum length of thread T (threaded flanges)

/** One size's row: the columns described above, in that order. */
export type B165Row = readonly [
  nps: number,
  O: number,
  tf: number,
  tfLap: number | null,
  R: number,
  X: number,
  holes: number,
  hole: number,
  W: number,
  bSO: number | null,
  bLap: number,
  A: number,
  ySO: number | null,
  yWN: number,
  yLap: number,
  r: number,
  q: number | null,
  d: number | null,
  t: number | null,
];

